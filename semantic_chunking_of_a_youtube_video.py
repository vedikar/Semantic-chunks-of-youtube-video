def is_correct(results, expected_start, expected_end):
    """
    Returns True if at least one of the top-k retrieved chunks
    overlaps with the expected correct timestamp range.
    """

    for result in results:

        retrieved_start = result["start"]
        retrieved_end = result["end"]

        # Check whether the retrieved chunk overlaps
        # with the expected timestamp range
        if (
            retrieved_start <= expected_end
            and retrieved_end >= expected_start
        ):
            return True

    return False


