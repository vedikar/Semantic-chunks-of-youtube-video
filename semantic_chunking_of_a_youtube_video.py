def create_chunks_from_segments(segments, max_seconds):

    new_chunks = []

    current_text = ""
    current_start = None
    current_end = None

    for segment in segments:

        start = segment["start"]
        end = segment["end"]
        text = segment["text"].strip()

        if current_start is None:
            current_start = start

        # If adding this segment would make the chunk too long
        if end - current_start > max_seconds:

            if current_text:
                new_chunks.append({
                    "text": current_text,
                    "start": current_start,
                    "end": current_end
                })

            # Start a new chunk with the current segment
            current_text = text
            current_start = start
            current_end = end

        else:

            if current_text:
                current_text += " " + text
            else:
                current_text = text

            current_end = end

    # Save final chunk
    if current_text:
        new_chunks.append({
            "text": current_text,
            "start": current_start,
            "end": current_end
        })

    return new_chunks


